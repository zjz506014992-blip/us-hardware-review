# 类型自检：递归断言无 tuple
def chk(o, path="root"):
    assert not isinstance(o, tuple), f"TUPLE at {path}"
    if isinstance(o, dict):
        for k, v in o.items(): chk(v, f"{path}.{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o): chk(v, f"{path}[{i}]")
chk(n)
